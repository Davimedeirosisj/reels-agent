export const recipes = table.map(([kind, defaults, behavior], i) => ({
  id: `A${String(i + 1).padStart(3, '0')}`,
  kind,
  defaults,
  behavior,
  status: behavior.startsWith('pending-')
    ? 'pending'
    : behavior.startsWith('partial-') || behavior.startsWith('approximate-')
      ? 'partial'
      : behavior.startsWith('requires-')
        ? 'requires-asset'
        : 'implemented-unverified',
}));
export function recipeById(id) {
  const r = recipes.find((x) => x.id === id);
  if (!r) throw new Error(`Recipe desconhecida: ${id}`);
  return r;
}
export function recipeEvent(id, params) {
  const r = recipeById(id);
  if (r.status === 'pending' || ['post', 'theme', 'camera', 'captions'].includes(r.kind))
    throw new Error(`${id} requer a etapa ${r.behavior}; não é um overlay`);
  return { ...r.defaults, ...params, kind: r.kind, recipeId: id };
}
